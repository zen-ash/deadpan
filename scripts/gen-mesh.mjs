// Generates packages/shared/src/mesh.ts: the subset of MediaPipe's 478 face landmarks that
// phones stream to the big screen, and the edges between them.
// Run from the repo root: node scripts/gen-mesh.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(new URL('../apps/web/package.json', import.meta.url));
const { FaceLandmarker: F } = await import(require.resolve('@mediapipe/tasks-vision'));

const groups = ['FACE_OVAL', 'LIPS', 'LEFT_EYE', 'RIGHT_EYE', 'LEFT_EYEBROW', 'RIGHT_EYEBROW', 'LEFT_IRIS', 'RIGHT_IRIS'];
const edges = groups.flatMap((g) => F[`FACE_LANDMARKS_${g}`].map((e) => [e.start, e.end]));
// A line down the nose bridge, so head turns read in 3D.
const nose = [168, 6, 197, 195, 5, 4, 1];
for (let i = 1; i < nose.length; i++) edges.push([nose[i - 1], nose[i]]);

const points = [...new Set(edges.flat())];
const slot = new Map(points.map((p, i) => [p, i]));
const local = edges.map(([a, b]) => [slot.get(a), slot.get(b)]);

const chunk = (arr, n) => Array.from({ length: Math.ceil(arr.length / n) }, (_, i) => arr.slice(i * n, i * n + n));
const out = `// Generated by scripts/gen-mesh.mjs from @mediapipe/tasks-vision. Do not edit by hand.

/** MediaPipe landmark indices streamed for the big-screen mesh, in stream order. */
export const MESH_POINTS: readonly number[] = [
${chunk(points, 16).map((r) => `  ${r.join(', ')},`).join('\n')}
];

/** Lines to draw, as pairs of positions in MESH_POINTS. */
export const MESH_EDGES: readonly number[] = [
${chunk(local.flat(), 24).map((r) => `  ${r.join(', ')},`).join('\n')}
];
`;
writeFileSync(new URL('../packages/shared/src/mesh.ts', import.meta.url), out);
console.log(`${points.length} points, ${local.length} edges`);

// Generates packages/shared/src/mesh.ts: the subset of MediaPipe's 478 face landmarks that
// phones stream to the big screen, and the edges between them. Also generates
// packages/shared/src/face.ts: the full tessellation and the feature contours, for the big
// screen's camera view (a separate module, so phones never download it).
// Run from the repo root: node scripts/gen-mesh.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(new URL('../apps/web/package.json', import.meta.url));
const { FaceLandmarker: F } = await import(require.resolve('@mediapipe/tasks-vision'));

const groups = ['FACE_OVAL', 'LIPS', 'LEFT_EYE', 'RIGHT_EYE', 'LEFT_EYEBROW', 'RIGHT_EYEBROW', 'LEFT_IRIS', 'RIGHT_IRIS'];
const edges = groups.flatMap((g) => F[`FACE_LANDMARKS_${g}`].map((e) => [e.start, e.end]));
// A line down the nose bridge, so head turns read in 3D.
const nose = [168, 6, 197, 195, 5, 4, 1];
for (let i = 1; i < nose.length; i++) edges.push([nose[i - 1], nose[i]]);

const points = [...new Set(edges.flat())];
const slot = new Map(points.map((p, i) => [p, i]));
const local = edges.map(([a, b]) => [slot.get(a), slot.get(b)]);

const chunk = (arr, n) => Array.from({ length: Math.ceil(arr.length / n) }, (_, i) => arr.slice(i * n, i * n + n));
const rows = (arr, n, indent = '  ') => chunk(arr, n).map((r) => `${indent}${r.join(', ')},`).join('\n');
const out = `// Generated by scripts/gen-mesh.mjs from @mediapipe/tasks-vision. Do not edit by hand.

/** MediaPipe landmark indices streamed for the big-screen mesh, in stream order. */
export const MESH_POINTS: readonly number[] = [
${rows(points, 16)}
];

/** Lines to draw, as pairs of positions in MESH_POINTS. */
export const MESH_EDGES: readonly number[] = [
${rows(local.flat(), 24)}
];
`;
writeFileSync(new URL('../packages/shared/src/mesh.ts', import.meta.url), out);
console.log(`mesh: ${points.length} points, ${local.length} edges`);

// The tessellation lists most triangle edges twice (once per neighbouring triangle).
const seen = new Set();
const tessellation = [];
for (const { start, end } of F.FACE_LANDMARKS_TESSELATION) {
  const key = start < end ? `${start},${end}` : `${end},${start}`;
  if (seen.has(key)) continue;
  seen.add(key);
  tessellation.push(start, end);
}
const part = (g) => F[`FACE_LANDMARKS_${g}`].flatMap((e) => [e.start, e.end]);
const parts = {
  leftEye: part('LEFT_EYE'),
  rightEye: part('RIGHT_EYE'),
  leftIris: part('LEFT_IRIS'),
  rightIris: part('RIGHT_IRIS'),
  leftBrow: part('LEFT_EYEBROW'),
  rightBrow: part('RIGHT_EYEBROW'),
  lips: part('LIPS'),
  oval: part('FACE_OVAL'),
};
const face = `// Generated by scripts/gen-mesh.mjs from @mediapipe/tasks-vision. Do not edit by hand.
// All indices are MediaPipe landmark numbers (0–477).

/** Every landmark the camera view streams: the full face mesh, irises included. */
export const FACE_LANDMARK_COUNT = 478;

/** The face mesh's triangle edges, as pairs of landmark indices. */
export const FACE_TESSELATION: readonly number[] = [
${rows(tessellation, 24)}
];

/** Feature outlines, as pairs of landmark indices. */
export const FACE_PARTS = {
${Object.entries(parts)
  .map(([k, v]) => `  ${k}: [\n${rows(v, 24, '    ')}\n  ],`)
  .join('\n')}
} as const satisfies Record<string, readonly number[]>;
`;
writeFileSync(new URL('../packages/shared/src/face.ts', import.meta.url), face);
console.log(`face: ${tessellation.length / 2} tessellation edges`);
